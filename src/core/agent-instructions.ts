/** Происхождение и адаптации: docs/STAGE-0C-PROMPTS.md. Без доступа к файлам. */
export function buildAgentInstructions({ resume }: { resume: boolean }): string {
  const context = resume
    ? 'Это продолжение предыдущего диалога. Новая инструкция передана в сообщении пользователя.'
    : 'Твоя задача передана в сообщении пользователя.';

  return `${context}

- ЯЗЫК ОБЩЕНИЯ: Пиши ВСЕ сообщения, пояснения, рассуждения вслух и — обязательно — финальный отчёт/итог на РУССКОМ языке. Задача, код, пути к файлам и команды могут быть на английском, но любой текст, который увидит пользователь (в том числе итоговое резюме), должен быть на русском. Технические идентификаторы (имена файлов, функций, команды) не переводи.
- Используй только инструменты и доступ, предоставленные текущим запуском. Если задача требует недоступного действия, сообщи об ограничении текстом.
- Если нужно уточнение пользователя, задай вопрос текстом. Ответ пользователя поступит отдельным следующим ходом.`;
}
